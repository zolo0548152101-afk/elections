-- Idempotent schema for election-day ops.
-- Does not truncate or delete streets, clusters, or any other rows.

CREATE TABLE IF NOT EXISTS settlements (
  name_he text PRIMARY KEY,
  lat double precision NOT NULL,
  lng double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS clusters (
  ashkol text PRIMARY KEY,
  settlement_name text NOT NULL,
  settlement_code text NOT NULL,
  bzb integer NOT NULL,
  voters integer NOT NULL,
  valid integer NOT NULL,
  right_votes integer NOT NULL,
  turnout_pct double precision NOT NULL,
  right_pct double precision NOT NULL,
  ballot_count integer NOT NULL
);

CREATE TABLE IF NOT EXISTS institutions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  kind text,
  settlement_name text,
  district text,
  lat double precision,
  lng double precision,
  key_people_raw text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE institutions ADD COLUMN IF NOT EXISTS kind text;
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS settlement_name text;
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS district text;
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS lat double precision;
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS lng double precision;
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS key_people_raw text;

CREATE TABLE IF NOT EXISTS institution_contacts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
  full_name text NOT NULL,
  role_title text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS institution_contacts_inst_idx
  ON institution_contacts (institution_id);

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  mobile text,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('super_admin', 'area_manager', 'coordinator')),
  institution_id integer REFERENCES institutions(id) ON DELETE SET NULL,
  manager_id integer REFERENCES users(id) ON DELETE SET NULL,
  settlement_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Ops copy of the permanent password for WhatsApp credential resend.
ALTER TABLE users ADD COLUMN IF NOT EXISTS login_password text;

-- One-time login code (5 digits, 5 minutes). Does not replace password_hash.
ALTER TABLE users ADD COLUMN IF NOT EXISTS temp_login_code_hash text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS temp_login_expires_at timestamptz;

CREATE TABLE IF NOT EXISTS sessions (
  id text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Legacy groups removed — product uses institutions only (חוברת2 + users.institution_id).
DROP TABLE IF EXISTS group_coordinators;
DROP TABLE IF EXISTS groups;

CREATE TABLE IF NOT EXISTS streets (
  id text PRIMARY KEY,
  name_he text NOT NULL,
  lat double precision NOT NULL,
  lng double precision NOT NULL,
  bbox_xmin double precision NOT NULL,
  bbox_ymin double precision NOT NULL,
  bbox_xmax double precision NOT NULL,
  bbox_ymax double precision NOT NULL,
  geom_geojson text NOT NULL,
  ashkol text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Per-user street done marks (a street can be done for one coordinator and open for another).
CREATE TABLE IF NOT EXISTS street_marks (
  street_id text NOT NULL REFERENCES streets(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  done boolean NOT NULL DEFAULT true,
  marked_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (street_id, user_id)
);

-- Migrate legacy global street_marks (street_id PK only) if still present.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'street_marks' AND column_name = 'marked_by'
  ) THEN
    CREATE TABLE IF NOT EXISTS street_marks_v2 (
      street_id text NOT NULL REFERENCES streets(id) ON DELETE CASCADE,
      user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      done boolean NOT NULL DEFAULT true,
      marked_at timestamptz NOT NULL DEFAULT now(),
      PRIMARY KEY (street_id, user_id)
    );
    INSERT INTO street_marks_v2 (street_id, user_id, done, marked_at)
    SELECT sm.street_id, sm.marked_by, sm.done, sm.marked_at
    FROM street_marks sm
    WHERE sm.marked_by IS NOT NULL
    ON CONFLICT DO NOTHING;
    DROP TABLE street_marks;
    ALTER TABLE street_marks_v2 RENAME TO street_marks;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS street_coordinators (
  street_id text NOT NULL REFERENCES streets(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  assigned_by integer REFERENCES users(id) ON DELETE SET NULL,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (street_id, user_id)
);

CREATE TABLE IF NOT EXISTS institution_clusters (
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
  ashkol text NOT NULL REFERENCES clusters(ashkol) ON DELETE CASCADE,
  linked_by integer REFERENCES users(id) ON DELETE SET NULL,
  linked_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (institution_id, ashkol)
);

-- Admin ops status for team clusters page (בוצע / לא בוצע), independent of street marks.
CREATE TABLE IF NOT EXISTS ashkol_ops_status (
  ashkol text PRIMARY KEY REFERENCES clusters(ashkol) ON DELETE CASCADE,
  done boolean NOT NULL DEFAULT false,
  updated_by integer REFERENCES users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Many-to-many: a coordinator may belong to several institutions.
CREATE TABLE IF NOT EXISTS institution_coordinators (
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  linked_by integer REFERENCES users(id) ON DELETE SET NULL,
  linked_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (institution_id, user_id)
);

CREATE INDEX IF NOT EXISTS institution_coordinators_user_idx
  ON institution_coordinators (user_id);

-- Backfill from legacy users.institution_id (idempotent).
INSERT INTO institution_coordinators (institution_id, user_id)
SELECT u.institution_id, u.id
FROM users u
WHERE u.role = 'coordinator'
  AND u.institution_id IS NOT NULL
ON CONFLICT DO NOTHING;

CREATE INDEX IF NOT EXISTS streets_ashkol_idx ON streets (ashkol);
CREATE INDEX IF NOT EXISTS streets_bbox_idx ON streets (bbox_xmin, bbox_xmax, bbox_ymin, bbox_ymax);
CREATE INDEX IF NOT EXISTS streets_name_he_idx ON streets (name_he);
CREATE INDEX IF NOT EXISTS street_coordinators_user_idx ON street_coordinators (user_id);
CREATE INDEX IF NOT EXISTS institution_clusters_ashkol_idx ON institution_clusters (ashkol);
CREATE INDEX IF NOT EXISTS street_marks_user_idx ON street_marks (user_id);

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX IF NOT EXISTS streets_name_he_trgm_idx ON streets USING gin (name_he gin_trgm_ops);
